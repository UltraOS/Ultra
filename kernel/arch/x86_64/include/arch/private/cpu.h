struct x86_cpu_info {
    u32 max_cpuid;
    u32 max_extended_cpuid;
    u8 family;
    u8 model;
    u8 stepping;

    u8 phys_bits;
    u8 virt_bits;

    char vendor[13];
    char name[48];

    union {
        u32 feature_dwords[X86_FEATURE_DWORD_COUNT];
        reg_t feature_bit_array[X86_FEATURE_UNIT_COUNT];
    };
};

/*
 * Lowest common denominator of features for all present CPUs, or simply the BSP
 * CPU info at early boot pre-SMP.
 */
extern struct x86_cpu_info g_cpu_info;
DECLARE_PER_CPU(struct x86_cpu_info, g_this_cpu_info);

/*
 * Global CPU feature tests always reference the early BSP CPU info, since all
 * APs AND mask their features into it when doing CPU detection.
 */
#define all_cpus_have(feature) bit_test(g_cpu_info.feature_bit_array, (feature))

#define this_cpu_has(feature) \
    bit_test(this_cpu_ptr(&g_this_cpu_info)->feature_bit_array, (feature))

