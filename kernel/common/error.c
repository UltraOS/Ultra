const char *error_to_string(error_t err)
{
    if (err < -MAX_ERRNO || err > MAX_ERRNO)
        return nullptr;

    if (err < 0)
        err = -err;

    if ((size_t)err >= ARRAY_SIZE(s_error_names))
        return nullptr;

    return s_error_names[err];
}
